def _parse_and_ingest(patents, scratch_graph_path):
    """Helper: parse each patent, write extracted nodes to a scratch
    graph file on disk, return the written graph."""
    from product.ingestion.patent_parser import PatentParser
    parser = PatentParser()

    # Load the real graph as a base.
    with open(ROOT / "data" / "civilization_graph.json") as f:
        graph = json.load(f)
    original_count = len(graph["nodes"])

    # Parse each patent and write nodes to disk.
    for patent_text, provenance in patents:
        result = parser.parse({
            "id": provenance["patent_number"],
            "text": patent_text,
            "provenance": provenance,
        })
        for comp in result.get("components", []):
            comp_id = f"ingested_{provenance['patent_number']}_{str(comp).lower().replace(' ', '_')}"
            if comp_id not in {n["id"] for n in graph["nodes"]}:
                graph["nodes"].append({
                    "id": comp_id,
                    "label": str(comp),
                    "type": "component",
                    "domain": "ingested",
                    "constraints": result.get("constraints", {}),
                    "provenance": provenance,
                    "status": "active",
                })

    # PERSIST TO DISK (the F-027 gap).
    with open(scratch_graph_path, "w") as f:
        json.dump(graph, f, indent=2)

    return graph, original_count


def test_ingest_3_patents_writes_to_disk_and_reread():
    """Phase 3 Step 2: ingest 3 real patent abstracts, write to a
    scratch graph file on disk, re-read, and verify."""
    with tempfile.TemporaryDirectory() as tmpdir:
        scratch_path = pathlib.Path(tmpdir) / "test_graph.json"
        patents = [
            (PATENT_1, PROVENANCE_1),
            (PATENT_2, PROVENANCE_2),
            (PATENT_3, PROVENANCE_3),
        ]
        graph, original_count = _parse_and_ingest(patents, scratch_path)

        # Verify the file was written to disk.
        assert scratch_path.exists(), "Scratch graph file was not written to disk"

        # RE-READ from disk (the F-027 gap).
        with open(scratch_path) as f:
            re_read = json.load(f)

        # Verify node count increased.
        new_count = len(re_read["nodes"])
        assert new_count > original_count, \
            f"No nodes added: was {original_count}, now {new_count}"
        assert new_count - original_count >= 5, \
            f"Expected >=5 new nodes, got {new_count - original_count}"


def test_ingested_nodes_have_provenance_after_disk_roundtrip():
    """F-027: provenance must survive disk write + re-read."""
    with tempfile.TemporaryDirectory() as tmpdir:
        scratch_path = pathlib.Path(tmpdir) / "test_graph.json"
        patents = [(PATENT_1, PROVENANCE_1)]
        _parse_and_ingest(patents, scratch_path)

        with open(scratch_path) as f:
            graph = json.load(f)

        ingested_nodes = [n for n in graph["nodes"]
                          if n.get("id", "").startswith("ingested_")]
        assert len(ingested_nodes) > 0, "No ingested nodes found after re-read"

        for node in ingested_nodes:
            prov = node.get("provenance")
            assert prov is not None, \
                f"Node {node['id']} has no provenance after disk round-trip"
            assert prov.get("patent_number") == "REAL-001"
            assert prov.get("source_type") == "patent"


