class TestJointDistributionConstraints:
    """The marginal-probability constraints p10 + p11 = pe and
    p01 + p11 = pr must hold for every admissible p11."""

    @pytest.mark.parametrize("pe,pr", [
        (0.5, 0.1), (0.6, 0.05), (0.7, 0.1), (0.3, 0.05),
    ])
    def test_marginal_constraints_hold(self, pe, pr):
        lo, hi = r4_1.feasible_p11_interval(pe, pr)
        # Sample several p11 values in the interior.
        for i in range(11):
            p11 = lo + (hi - lo) * i / 10
            p00, p01, p10, p11_actual = r4_1.joint_from_p11(pe, pr, p11)
            assert abs((p10 + p11_actual) - pe) < 1e-9, (
                f"p10 + p11 != pe: {p10} + {p11_actual} != {pe}"
            )
            assert abs((p01 + p11_actual) - pr) < 1e-9, (
                f"p01 + p11 != pr: {p01} + {p11_actual} != {pr}"
            )
            assert abs((p00 + p01 + p10 + p11_actual) - 1.0) < 1e-9, (
                f"Probabilities do not sum to 1: "
                f"{p00} + {p01} + {p10} + {p11_actual} = "
                f"{p00 + p01 + p10 + p11_actual}"
            )
            assert p00 >= -1e-12, f"p00 < 0: {p00}"
            assert p01 >= -1e-12, f"p01 < 0: {p01}"
            assert p10 >= -1e-12, f"p10 < 0: {p10}"
            assert p11_actual >= -1e-12, f"p11 < 0: {p11_actual}"


