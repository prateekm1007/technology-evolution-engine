class TestPolynomialConstruction:
    """Verify that power_polynomial(pe, pr)(p11) matches the direct
    computation power_at_p11(pe, pr, p11) for all tested (pe, pr, p11).

    This is the foundational correctness test for the certified method.
    If the polynomial construction is wrong, every certified extremum
    is wrong. The grid-search cross-check in search_power_extrema
    catches gross errors, but this test catches them at a finer grain.
    """

    @pytest.mark.parametrize("pe,pr", [
        (0.50, 0.10), (0.50, 0.05), (0.60, 0.10), (0.60, 0.05),
        (0.70, 0.10), (0.40, 0.10), (0.30, 0.05), (0.20, 0.00),
        (0.10, 0.10), (0.50, 0.50), (0.70, 0.70),
    ])
    def test_polynomial_matches_direct_computation(self, pe, pr):
        """For several p11 values in the feasible interval, the
        polynomial-evaluated power must match the direct computation.

        Tolerance is 1e-6 (not 1e-9) because:
        1. The polynomial multiplies large multinomial coefficients
           (up to ~3.5M for N=20) in double precision, while the direct
           computation uses log-space (math.lgamma, math.exp).
        2. At boundary points (e.g., p11 = hi), pe - p11 can be a tiny
           negative number like -1.11e-16 (not exactly 0) due to binary
           floating-point representation. The direct computation clamps
           this to 0, but the polynomial evaluates it directly, producing
           a tiny residual ~1e-7.

        A tolerance of 1e-6 accommodates both effects while still being
        100x tighter than the 1e-4 grid-search agreement threshold used
        for certified extrema certification.
        """
        lo, hi = r4_1.feasible_p11_interval(pe, pr)
        poly = r4_1.power_polynomial(pe, pr)
        # Test at 11 points across the feasible interval.
        for i in range(11):
            p11 = lo + (hi - lo) * i / 10
            poly_val = float(poly(p11))
            direct_val = r4_1.power_at_p11(pe, pr, p11)
            assert abs(poly_val - direct_val) < 1e-6, (
                f"Polynomial mismatch at pe={pe}, pr={pr}, p11={p11}: "
                f"poly={poly_val:.12f}, direct={direct_val:.12f}, "
                f"diff={abs(poly_val - direct_val):.2e}"
            )

    def test_polynomial_matches_at_endpoints(self):
        """The polynomial must match direct computation at both
        endpoints of the feasible interval."""
        pe, pr = 0.50, 0.10
        lo, hi = r4_1.feasible_p11_interval(pe, pr)
        poly = r4_1.power_polynomial(pe, pr)
        assert abs(float(poly(lo)) - r4_1.power_at_p11(pe, pr, lo)) < 1e-6
        assert abs(float(poly(hi)) - r4_1.power_at_p11(pe, pr, hi)) < 1e-6

    def test_polynomial_matches_at_interior_extremum(self):
        """For pe=0.40, pr=0.10, the certified interior extremum is
        at p11 ≈ 0.0474. The polynomial must match direct computation
        at this exact point."""
        pe, pr = 0.40, 0.10
        poly = r4_1.power_polynomial(pe, pr)
        certified = r4_1.certified_extrema(pe, pr)
        # Find the interior stationary point
        assert certified["n_stationary_points"] >= 1, (
            "Expected at least 1 stationary point for pe=0.40, pr=0.10"
        )
        sp = certified["stationary_points"][0]["p11"]
        poly_val = float(poly(sp))
        direct_val = r4_1.power_at_p11(pe, pr, sp)
        assert abs(poly_val - direct_val) < 1e-6, (
            f"Polynomial mismatch at interior extremum p11={sp}: "
            f"poly={poly_val:.12f}, direct={direct_val:.12f}"
        )


