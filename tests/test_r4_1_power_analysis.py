class TestExtremaAreActualMinMax:
    """The central statistical correction: extrema are NOT assumed to
    occur at endpoints. The script must search the interior.

    This is the test that catches the R4.1 defect: R4.1 assumed
    p11 = min(pe, pr) gives the worst case and p11 = 0 gives the best
    case. That assumption is invalid for the combined decision rule.
    """

    def test_search_uses_dense_grid(self):
        """The script must evaluate power at > 2 points (not just
        endpoints). A grid of P11_GRID_SIZE = 1001 is used."""
        assert r4_1.P11_GRID_SIZE > 100, (
            "Grid must be dense (>100 points), not just endpoints."
        )

    def test_pe040_pr010_max_is_at_interior(self):
        """For pe=0.40, pr=0.10, theta=0.30, the power maximum is at
        an INTERIOR point of the feasible p11 interval, not at an
        endpoint. This is direct mechanical proof that endpoint-only
        reasoning is invalid.

        Reproduction: at the time of writing, the argmax p11 ≈ 0.0474,
        which is in the interior of [0, 0.1]."""
        row = r4_1.search_power_extrema(0.40, 0.10)
        assert row["p11_lo"] < row["p11_at_max"] < row["p11_hi"], (
            f"For pe=0.40, pr=0.10, the power MAXIMUM must be at an "
            f"interior point. Got p11_at_max={row['p11_at_max']} "
            f"in [{row['p11_lo']}, {row['p11_hi']}]."
        )

    def test_pe050_pr010_min_is_at_p11_zero_not_at_min(self):
        """For pe=0.50, pr=0.10, theta=0.40 (the FIRST row of R4.1's
        table), R4.1 claimed the worst case is at p11 = min(pe, pr) = 0.1.

        Mechanically, the worst case is at p11 = 0, NOT at p11 = 0.1.
        This is the row that 'is enough to kill the freeze' per the
        external audit."""
        row = r4_1.search_power_extrema(0.50, 0.10)
        assert row["p11_at_min"] == 0.0, (
            f"For pe=0.50, pr=0.10, the power MINIMUM is at p11=0 "
            f"(not at p11=min(pe,pr)=0.1 as R4.1 claimed). "
            f"Got p11_at_min={row['p11_at_min']}."
        )
        assert row["p11_at_max"] == 0.1, (
            f"For pe=0.50, pr=0.10, the power MAXIMUM is at p11=0.1 "
            f"(which R4.1 thought was the WORST case). "
            f"Got p11_at_max={row['p11_at_max']}."
        )

    def test_extrema_are_global_not_local(self):
        """For each scenario, verify that no point on the grid gives
        power below power_min or above power_max. This catches
        off-by-one errors in the argmin/argmax search."""
        for pe, pr in r4_1.POWER_SCENARIOS:
            row = r4_1.search_power_extrema(pe, pr)
            lo, hi = r4_1.feasible_p11_interval(pe, pr)
            # Re-evaluate at 50 random-ish points across the interval.
            for i in range(50):
                p11 = lo + (hi - lo) * i / 49
                p = r4_1.power_at_p11(pe, pr, p11)
                assert p >= row["power_min"] - 1e-9, (
                    f"Found power {p} below reported power_min "
                    f"{row['power_min']} at p11={p11} for "
                    f"pe={pe}, pr={pr}"
                )
                assert p <= row["power_max"] + 1e-9, (
                    f"Found power {p} above reported power_max "
                    f"{row['power_max']} at p11={p11} for "
                    f"pe={pe}, pr={pr}"
                )


