class TestProbabilityMassConservation:
    """The multinomial marginal over (b, c) must sum to 1.0 for every
    admissible (p10, p01) pair. If it does not, the enumerator is
    missing outcomes and every power calculation is wrong."""

    @pytest.mark.parametrize("p10,p01", [
        (0.5, 0.1),    # R4.1 row 1 at p11=0
        (0.4, 0.0),    # R4.1 row 1 at p11=0.1
        (0.6, 0.05),
        (0.3, 0.0),
        (0.1, 0.1),    # symmetric
        (0.0, 0.0),    # degenerate: all concordant
        (0.5, 0.5),    # degenerate: no concordant
    ])
    def test_probability_mass_equals_one(self, p10, p01):
        """sum_{b, c : b+c <= N} P(b, c) must equal 1.0."""
        if p10 + p01 > 1.0 + 1e-12:
            pytest.skip("infeasible probability combination")
        total = sum(
            r4_1.multinomial_pmf_b_c(b, c, p10, p01, r4_1.N)
            for b in range(r4_1.N + 1)
            for c in range(r4_1.N + 1 - b)
        )
        assert abs(total - 1.0) < 1e-9, (
            f"Probability mass does not sum to 1.0 for "
            f"(p10={p10}, p01={p01}): got {total}"
        )

    def test_probability_mass_one_at_degenerate_p11(self):
        """When p11 = min(pe, pr) = pr (so p01 = 0), all discordant
        mass is on (b, 0). The sum over (b, 0) must equal
        sum_{b=0}^{N} Binom(N, p10) = 1.0."""
        pe, pr = 0.5, 0.1
        p11 = min(pe, pr)  # = 0.1
        p10 = pe - p11     # = 0.4
        p01 = pr - p11     # = 0.0
        total = sum(
            r4_1.multinomial_pmf_b_c(b, 0, p10, p01, r4_1.N)
            for b in range(r4_1.N + 1)
        )
        assert abs(total - 1.0) < 1e-9


