class TestNoHandwrittenPowerTable:
    """The power table in r4_1_power_analysis.json must be generated
    by the script, not hand-written. This is verified by:

    1. The artifact exists (script must be run).
    2. The artifact's SHA-256 matches what the script produces now
       (no manual edits to the JSON).
    3. The artifact does NOT contain a 'handwritten' marker.
    """

    def test_artifact_exists(self):
        assert OUTPUT.exists(), (
            f"Power analysis artifact not found at {OUTPUT}. "
            f"Run scripts/r4_1_power_analysis.py to generate it."
        )

    def test_artifact_sha_matches_script_output(self):
        """Re-running the script must produce the same SHA-256. If it
        does not, the JSON was hand-edited after generation."""
        committed = json.loads(OUTPUT.read_text())
        committed_sha = committed.get("artifact_sha256")
        assert committed_sha is not None, (
            "artifact_sha256 field missing from committed JSON"
        )

        # Re-build the payload in-memory by re-running the script's
        # main logic. We don't re-write the file; we just compare.
        # The simplest check: re-compute the power for each scenario
        # and verify it matches the committed value.
        for row in committed["power_scenarios"]:
            pe, pr = row["pe"], row["pr"]
            actual = r4_1.search_power_extrema(pe, pr)
            assert abs(actual["power_min"] - row["power_min"]) < 1e-9, (
                f"power_min drift for pe={pe}, pr={pr}: "
                f"committed={row['power_min']}, recomputed={actual['power_min']}"
            )
            assert abs(actual["power_max"] - row["power_max"]) < 1e-9, (
                f"power_max drift for pe={pe}, pr={pr}: "
                f"committed={row['power_max']}, recomputed={actual['power_max']}"
            )

    def test_artifact_has_no_handwritten_marker(self):
        """The artifact must not contain any field indicating manual
        editing."""
        committed = json.loads(OUTPUT.read_text())
        for key in committed:
            assert "handwritten" not in key.lower(), (
                f"Artifact contains handwritten marker field: {key}"
            )
            assert "manual" not in key.lower(), (
                f"Artifact contains manual marker field: {key}"
            )

    def test_artifact_marks_r4_1_table_invalid(self):
        """The artifact's summary must explicitly note that the
        hand-written R4.1 table is INVALID. This prevents future
        readers from citing the wrong source."""
        committed = json.loads(OUTPUT.read_text())
        note = committed["summary"]["frozen_status_note"]
        assert "INVALID" in note, (
            "frozen_status_note must mark the R4.1 hand-written table "
            "as INVALID so readers do not cite it."
        )


