class TestCombinedRuleMatchesProtocol:
    """The decision rule must be EXACTLY:
        p_one_sided < 0.05 AND ci_lower > 0.20

    No more, no less. The rule must match r4_reference_vectors.py
    exactly (single source of truth).
    """

    def test_passes_rule_uses_both_gates(self):
        """passes_combined_rule must return True iff BOTH conditions
        hold."""
        # (b=12, c=1) passes both: p=0.0017 < 0.05, CI_lower=0.267 > 0.20
        assert r4_1.passes_combined_rule(12, 1) is True
        # (b=9, c=1) fails CI gate: p=0.011 < 0.05, CI_lower=0.119 < 0.20
        assert r4_1.passes_combined_rule(9, 1) is False
        # (b=8, c=2) fails p gate: p=0.055 > 0.05, CI_lower=-0.006 < 0.20
        assert r4_1.passes_combined_rule(8, 2) is False
        # (b=14, c=0) passes both: p=6.1e-5 < 0.05, CI_lower=0.474 > 0.20
        assert r4_1.passes_combined_rule(14, 0) is True

    def test_passes_rule_matches_reference_vectors(self):
        """For each frozen reference vector, passes_combined_rule must
        return the same value as the committed vector's 'passes' field."""
        committed = json.loads(REFERENCE_VECTORS.read_text())
        for v in committed["vectors"]:
            actual = r4_1.passes_combined_rule(v["b"], v["c"])
            assert actual == v["passes"], (
                f"passes mismatch for (b={v['b']}, c={v['c']}): "
                f"script={actual}, committed={v['passes']}"
            )

    def test_combined_rule_type_i_upper_bound_holds(self):
        """Under H0 (pe = pr), the combined rule's Type-I error rate
        must be ≤ alpha = 0.05. The protocol claims:

            P(p < 0.05 AND CI_lower > 0.20 | H0) ≤ P(p < 0.05 | H0) ≤ 0.05

        This test verifies the claim mechanically across all null
        scenarios."""
        for pe, pr in r4_1.TYPE_I_SCENARIOS:
            row = r4_1.search_power_extrema(pe, pr)
            assert row["power_max"] <= 0.05 + 1e-9, (
                f"Type-I error exceeds alpha=0.05 for pe=pr={pe}: "
                f"max Type-I = {row['power_max']}"
            )


