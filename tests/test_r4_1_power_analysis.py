        # The stationary point must be in the interior (not at endpoints).
        lo, hi = r4_1.feasible_p11_interval(0.40, 0.10)
        sp = certified["stationary_points"][0]["p11"]
        assert lo < sp < hi, (
            f"Stationary point p11={sp} must be in the interior of "
            f"[{lo}, {hi}]"
        )
        # The certified argmax must match this stationary point.
        row = r4_1.search_power_extrema(0.40, 0.10)
        assert abs(row["p11_at_max"] - sp) < 1e-9, (
            f"Certified argmax p11={row['p11_at_max']} must match "
            f"the interior stationary point p11={sp}"
        )

