class TestP11FeasibleInterval:
    """The feasible p11 interval is [max(0, pe+pr-1), min(pe, pr)].
    Outside this interval, the joint distribution is infeasible."""

    @pytest.mark.parametrize("pe,pr,expected_lo,expected_hi", [
        (0.5, 0.1, 0.0, 0.1),    # pe + pr < 1, so lo = 0
        (0.6, 0.5, 0.1, 0.5),    # pe + pr > 1, so lo = pe+pr-1 = 0.1
        (0.7, 0.7, 0.4, 0.7),    # symmetric, lo = 2p - 1
        (0.0, 0.0, 0.0, 0.0),    # degenerate
        (1.0, 1.0, 1.0, 1.0),    # all YES
        (1.0, 0.0, 0.0, 0.0),    # engine always YES, retrieval always NO
    ])
    def test_feasible_interval_bounds(self, pe, pr, expected_lo, expected_hi):
        lo, hi = r4_1.feasible_p11_interval(pe, pr)
        assert abs(lo - expected_lo) < 1e-9, (
            f"lo wrong: got {lo}, expected {expected_lo}"
        )
        assert abs(hi - expected_hi) < 1e-9, (
            f"hi wrong: got {hi}, expected {expected_hi}"
        )

    def test_infeasible_p11_gives_zero_power(self):
        """If we pass an infeasible p11, power should be 0 (because
        the multinomial probabilities are zero)."""
        # pe=0.5, pr=0.1, feasible p11 in [0, 0.1].
        # p11 = 0.2 is infeasible (would require p01 = -0.1).
        p = r4_1.power_at_p11(0.5, 0.1, 0.2)
        assert p == 0.0


