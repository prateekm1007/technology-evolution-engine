class TestAuditNumberReproduction:
    """Reproduce the exact numbers from the external audit (round 35).

    The auditor independently evaluated the complete paired-multinomial
    distribution under the exact R4.1 decision rule and reported:

        | Engine | Retrieval | Actual minimum | Actual maximum |
        |   0.50 |      0.10 |          28.3% |          40.4% |
        |   0.50 |      0.05 |          46.3% |          58.6% |
        |   0.60 |      0.10 |          49.3% |          74.8% |
        |   0.60 |      0.05 |          69.7% |          86.9% |
        |   0.70 |      0.10 |          70.7% |          94.3% |

    This test class verifies the script reproduces those numbers
    mechanically. If any number drifts, the script has a regression.
    """

    @pytest.mark.parametrize("pe,pr,expected_min_pct,expected_max_pct", [
        (0.50, 0.10, 0.283, 0.404),
        (0.50, 0.05, 0.463, 0.586),
        (0.60, 0.10, 0.493, 0.748),
        (0.60, 0.05, 0.697, 0.869),
        (0.70, 0.10, 0.707, 0.943),
    ])
    def test_audit_numbers_reproduced(self, pe, pr,
                                       expected_min_pct, expected_max_pct):
        """The script's power_min and power_max must match the
        auditor's independent calculation to within 0.5 percentage
        points (rounding tolerance)."""
        row = r4_1.search_power_extrema(pe, pr)
        # The auditor rounded to 1 decimal place in percentage form,
        # so 28.3% means 0.283 ± 0.0005.
        assert abs(row["power_min"] - expected_min_pct) < 0.005, (
            f"power_min for pe={pe}, pr={pr}: "
            f"got {row['power_min']:.4f}, auditor reported {expected_min_pct:.4f}"
        )
        assert abs(row["power_max"] - expected_max_pct) < 0.005, (
            f"power_max for pe={pe}, pr={pr}: "
            f"got {row['power_max']:.4f}, auditor reported {expected_max_pct:.4f}"
        )

    def test_r4_1_claimed_worst_case_is_actually_best_case(self):
        """The R4.1 document claims that for pe=0.50, pr=0.10, the
        worst-case power is <1% (at p11 = min(pe, pr) = 0.1).

        Mechanically, p11 = 0.1 is where power is MAXIMIZED (40.4%),
        not minimized. The worst case is at p11 = 0 (28.3%).

        This is the central defect in R4.1: the worst-case and
        best-case labels are reversed."""
        pe, pr = 0.50, 0.10
        p11_worst_per_r41 = min(pe, pr)  # = 0.1
        p11_best_per_r41 = 0.0
        power_at_r41_worst = r4_1.power_at_p11(pe, pr, p11_worst_per_r41)
        power_at_r41_best = r4_1.power_at_p11(pe, pr, p11_best_per_r41)

        # R4.1 said power_at_p11=0.1 is <1%. Actually it's ~40%.
        assert power_at_r41_worst > 0.30, (
            f"R4.1 claimed power at p11=min(pe,pr) is <1%, but it is "
            f"actually {power_at_r41_worst:.4f}. The R4.1 'worst case' "
            f"label is wrong."
        )
        # R4.1 said power_at_p11=0 is 38%. Actually it's ~28%.
        # So the labels are reversed: p11=0 is WORSE than p11=0.1.
        assert power_at_r41_best < power_at_r41_worst, (
            f"R4.1 claimed p11=0 is the best case, but p11=0 "
            f"(power={power_at_r41_best:.4f}) is actually WORSE than "
            f"p11=0.1 (power={power_at_r41_worst:.4f}). The R4.1 "
            f"best/worst labels are reversed."
        )

    def test_r4_1_power_table_is_not_trustworthy(self):
        """The R4.1 document's power table is mechanically refuted.

        R4.1 claims (row 1): power worst <1%, power best 38%.
        Actual: power worst 28.3%, power best 40.4%.

        The R4.1 worst-case claim is off by a factor of ~28x. This
        test exists to prevent anyone from re-citing the R4.1 table
        without first reading this script's output."""
        row = r4_1.search_power_extrema(0.50, 0.10)
