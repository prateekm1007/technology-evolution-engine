@dataclass
class DiscoveredLaw:
    """The law discovered by BACON for a given (x, y) dataset.

    Fields mirror invention_compiler.discovery_graph.Law where applicable
    so the discovered law can be promoted into the DiscoveryGraph.
    """
    name: str                  # candidate name, e.g., "power"
    form: str                  # human-readable form, e.g., "y = a * x^b"
    params: List[float]        # fitted coefficients
    param_names: List[str]
    r2: float                  # coefficient of determination in [0, 1]
    residuals: List[float]    # per-point residuals
    n_points: int              # number of data points
    falsifiable_by: str        # how to falsify this law

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "form": self.form,
            "params": self.params,
            "param_names": self.param_names,
            "r2": self.r2,
            "n_points": self.n_points,
            "falsifiable_by": self.falsifiable_by,
            "max_residual": max(abs(r) for r in self.residuals) if self.residuals else 0.0,
        }

    def __str__(self) -> str:
        param_strs = [f"{n}={p:.6g}" for n, p in zip(self.param_names, self.params)]
        return (f"DiscoveredLaw(name={self.name}, form='{self.form}', "
                f"params=[{', '.join(param_strs)}], R²={self.r2:.4f}, "
                f"n_points={self.n_points})")


# ---------------------------------------------------------------------------
# BACON engine
# ---------------------------------------------------------------------------

# Falsifiability threshold: a law with R² below this is rejected.
# Per "no data, say no data" principle: a weak fit is reported as no-fit.
R2_FALSIFIABILITY_THRESHOLD = 0.5


def discover_law(xs: List[float], ys: List[float],
                 x_label: str = "x", y_label: str = "y",
                 threshold: float = R2_FALSIFIABILITY_THRESHOLD,
                 verbose: bool = False
                 ) -> Optional[DiscoveredLaw]:
    """Discover the best-fitting law from (x, y) data.

    Tries every candidate law form in CANDIDATE_LAWS, fits each by
    least-squares, and returns the one with the highest R² that exceeds
    the threshold. If no candidate meets the threshold, returns None
    (no law preferred over a weak fit — per "no data, say no data").

    Args:
        xs: input data (independent variable)
        ys: output data (dependent variable)
        x_label: name of the x variable (for falsification description)
        y_label: name of the y variable (for falsification description)
        threshold: minimum R² required for a law to be accepted
        verbose: if True, print fit results for every candidate

    Returns:
        DiscoveredLaw if a candidate exceeds the threshold, else None.
    """
    if len(xs) != len(ys):
        raise ValueError(f"length mismatch: {len(xs)} xs vs {len(ys)} ys")
    if len(xs) < 3:
        # Cannot meaningfully fit a 2-parameter law with fewer than 3 points
        return None

    best: Optional[DiscoveredLaw] = None
    best_r2: float = threshold  # must EXCEED the threshold to be accepted

    for candidate in CANDIDATE_LAWS:
        try:
            params, r2, residuals = candidate.fit_func(xs, ys)
        except (ValueError, OverflowError, ZeroDivisionError):
            # Some candidates are undefined for certain data (e.g., log of negative)
            if verbose:
                print(f"  {candidate.name:12s} — undefined for this data, skipped")
            continue

        if verbose:
            param_strs = [f"{n}={p:.4g}" for n, p in zip(candidate.param_names, params)]
            print(f"  {candidate.name:12s} R²={r2:.4f}  params=[{', '.join(param_strs)}]")

        if r2 > best_r2:
            best_r2 = r2
            best = DiscoveredLaw(
                name=candidate.name,
                form=candidate.form,
                params=params,
                param_names=list(candidate.param_names),
                r2=r2,
                residuals=residuals,
                n_points=len(xs),
                falsifiable_by=(
                    f"Measure ({x_label}, {y_label}) at a value not in the training set. "
                    f"If the predicted {y_label} differs from observed by more than "
                    f"{max(abs(r) for r in residuals):.4g}, the law is falsified."
                ),
            )

    return best


def discover_laws_from_dataset(dataset: Dict[str, List[float]],
                                target_var: str,
                                independent_vars: Optional[List[str]] = None,
                                threshold: float = R2_FALSIFIABILITY_THRESHOLD,
                                verbose: bool = False
                                ) -> Dict[str, Optional[DiscoveredLaw]]:
    """Discover laws between each independent variable and the target.

    For multivariate data, BACON tries to discover the best law between
    each (independent_var, target) pair. This is the simple version of
    Langley's BACON.1: it does not compose variables (BACON.3) or
    discover hidden variables (BACON.4) — those are Phase IV.

    Args:
        dataset: dict mapping variable name → list of values
        target_var: the dependent variable to discover laws for
        independent_vars: list of vars to try as predictors (default: all
            vars except target_var)
        threshold: minimum R² required
        verbose: if True, print fit details

    Returns:
        dict mapping independent_var → DiscoveredLaw (or None if no law fits)
    """
    if target_var not in dataset:
        raise ValueError(f"target_var '{target_var}' not in dataset")
    if independent_vars is None:
        independent_vars = [v for v in dataset if v != target_var]

    results: Dict[str, Optional[DiscoveredLaw]] = {}
    for var in independent_vars:
        if var not in dataset:
            continue
        if len(dataset[var]) != len(dataset[target_var]):
            continue
        law = discover_law(dataset[var], dataset[target_var],
                           x_label=var, y_label=target_var,
                           threshold=threshold, verbose=verbose)
        results[var] = law
    return results


