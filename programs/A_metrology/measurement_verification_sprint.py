def _git_commit():
    """Get current git commit."""
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=REPO, text=True
        ).strip()[:12]
    except Exception:
        return "unknown"


def _git_log_for_file(filepath):
    """Get last commit that modified a file."""
    try:
        return subprocess.check_output(
            ["git", "log", "-1", "--format=%H %s", "--", filepath],
            cwd=REPO, text=True
        ).strip()
    except Exception:
        return "unknown"


