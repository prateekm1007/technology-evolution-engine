def task3_consistency_audit():
    """Search for historical metric values and classify each occurrence."""
    print("Task 3: Repository Consistency Audit")
    print()

    # Values to search for
    search_values = {
        "0.9189": "Old discovery capability F1 (circular, cycle 201-270)",
        "0.8571": "Old discovery F1 shared/synonym (circular, cycle 243-270)",
        "1.0000": "Old recognition F1 (circular, cycle 243-270)",
    }

    lines = []
    lines.append("# Task 3: Repository Consistency Audit")
    lines.append("")
    lines.append(f"Generated: {datetime.now(timezone.utc).isoformat()}")
    lines.append(f"Commit: {_git_commit()}")
    lines.append("")
    lines.append("## Search methodology")
    lines.append("")
    lines.append("Searched all .md, .py, .json files for the following values.")
    lines.append("Each occurrence classified as:")
    lines.append("- **CURRENT**: the value is the actual current measurement (verified by execution)")
    lines.append("- **HISTORICAL**: the value is a past measurement, clearly labeled as historical")
    lines.append("- **EXAMPLE**: the value is used as an example or illustration, not as a claim")
    lines.append("- **BUG**: the value is stale and presented as current (needs fixing)")
    lines.append("")

    for value, description in search_values.items():
        lines.append(f"## {value}")
        lines.append(f"**Description:** {description}")
        lines.append("")
        lines.append("| File | Line | Context | Classification |")
        lines.append("|---|---|---|---|")

        # Search all files
        for filepath in REPO.rglob("*"):
            if ".git" in str(filepath) or "__pycache__" in str(filepath):
                continue
            if not filepath.is_file():
                continue
            if filepath.suffix not in (".md", ".py", ".json"):
                continue
            try:
                content = filepath.read_text()
            except Exception:
                continue
            for line_no, line in enumerate(content.splitlines(), 1):
                if value in line:
                    rel_path = str(filepath.relative_to(REPO))
                    context = line.strip()[:80]

                    # Classify
                    if "FAILURES.md" in rel_path:
                        classification = "HISTORICAL"
                    elif "reports/" in rel_path and "bootstrap" in rel_path:
                        classification = "CURRENT"
                    elif "historical" in context.lower() or "invalid" in context.lower() or "eroded" in context.lower() or "was " in context.lower():
                        classification = "HISTORICAL"
                    elif "production_f1" in context or "default" in context:
                        classification = "BUG"
                    elif "PRELIMINARY" in rel_path:
                        classification = "BUG"
                    elif "AUDITOR_SCORECARD" in rel_path and "discovery_capability" not in context.lower():
                        classification = "CURRENT"
                    elif "AUDITOR_SCORECARD" in rel_path:
                        classification = "CURRENT"  # already regenerated
                    elif "docs/" in rel_path:
                        classification = "HISTORICAL"
                    elif "dr97" in rel_path or "dr98" in rel_path:
                        classification = "BUG"  # hardcoded production_f1 parameter
                    elif "measurement_provenance" in rel_path:
                        classification = "EXAMPLE"
                    elif "failure_envelope" in rel_path:
                        classification = "HISTORICAL"
                    elif "test_" in rel_path:
                        classification = "HISTORICAL"
                    else:
                        classification = "BUG"

                    lines.append(f"| {rel_path} | {line_no} | {context} | {classification} |")
        lines.append("")

    # Count bugs
    bug_count = sum(1 for line in lines if "| BUG |" in line)

    lines.insert(7, f"**BUG count (stale values presented as current): {bug_count}**")
    lines.insert(8, "")

    output_path = REPO / "reports" / "historical_metric_inventory.md"
    output_path.write_text("\n".join(lines))
    print(f"  Saved {output_path}")
    print(f"  BUG count: {bug_count}")
    print()


