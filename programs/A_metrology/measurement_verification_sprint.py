def task2_dependency_audit():
    """Generate a complete dependency graph for every measurement."""
    print("Task 2: Dependency Audit")
    print()

    # Load bootstrap data to get all metric IDs
    bootstrap_path = REPO / "reports" / "bootstrap_statistics.json"
    bootstrap_data = json.loads(bootstrap_path.read_text())
    metric_ids = [r["metric_id"] for r in bootstrap_data.get("results", [])]

    # For each metric, trace: producer, consumers, reports, tests, historical refs
    lines = []
    lines.append("# Task 2: Measurement Dependency Graph")
    lines.append("")
    lines.append(f"Generated: {datetime.now(timezone.utc).isoformat()}")
    lines.append(f"Commit: {_git_commit()}")
    lines.append("")

    for mid in metric_ids:
        lines.append(f"## {mid}")
        lines.append("")

        # Find producer (which .py file computes this metric)
        producers = []
        for py_file in REPO.rglob("*.py"):
            if "__pycache__" in str(py_file):
                continue
            try:
                content = py_file.read_text()
                if mid in content or mid.replace("-", "_") in content:
                    producers.append(str(py_file.relative_to(REPO)))
            except Exception:
                pass

        # Find consumers (reports that reference this metric)
        consumers = []
        for report_file in (REPO / "reports").rglob("*.json"):
            try:
                content = report_file.read_text()
                if mid in content:
                    consumers.append(str(report_file.relative_to(REPO)))
            except Exception:
                pass

        # Find tests
        tests = []
        for test_file in (REPO / "tests").glob("*.py"):
            try:
                content = test_file.read_text()
                if mid in content:
                    tests.append(str(test_file.relative_to(REPO)))
            except Exception:
                pass

        # Find docs that cite this metric
        docs = []
        for md_file in REPO.rglob("*.md"):
            if ".git" in str(md_file) or "node_modules" in str(md_file):
                continue
            try:
                content = md_file.read_text()
                if mid in content:
                    docs.append(str(md_file.relative_to(REPO)))
            except Exception:
                pass

        lines.append(f"**Producer:** {producers[0] if producers else 'UNKNOWN'}")
        lines.append(f"**Reports:** {', '.join(consumers[:5]) if consumers else 'none'}")
        lines.append(f"**Tests:** {', '.join(tests[:3]) if tests else 'none'}")
        lines.append(f"**Docs:** {', '.join(docs[:3]) if docs else 'none'}")
        lines.append("")

    output_path = REPO / "reports" / "measurement_dependency_graph.md"
    output_path.write_text("\n".join(lines))
    print(f"  Saved {output_path} ({len(metric_ids)} metrics)")
    print()


